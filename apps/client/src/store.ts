/**
 * Память прибора.
 *
 * Браузер может запретить сайту хранить что бы то ни было — и запрещает
 * чаще, чем кажется: строгие настройки Safari, встроенные браузеры внутри
 * приложений, «инкогнито» у части клиентов. Обращение к `localStorage` там
 * не возвращает пустоту, а **бросает исключение** — и роняет ту строку, на
 * которой стоит. Игра при этом успевала нарисовать корпус и умирала на
 * чтении темы: чёрное поле, ни точки, и ни слова о причине.
 *
 * Поэтому в прибор память ходит только отсюда. Правила два:
 *
 * 1. **Ничего не бросаем.** Не прочиталось — значит, ничего не сохранено;
 *    не записалось — значит, до следующего запуска не доживёт. Ни то, ни
 *    другое не повод не играть.
 * 2. **Запасная память на вкладку.** Когда хранилище закрыто, записанное
 *    ложится в обычный объект: до перезагрузки прибор помнит и тему, и
 *    токен, и выбранные шильдики — то есть игра работает целиком, а
 *    теряется только память между запусками. Без этого закрытое хранилище
 *    означало бы новый гостевой аккаунт на каждое нажатие.
 */

/** Запасная память: живёт, пока открыта вкладка. */
const fallback = new Map<string, string>();

/** Доступно ли настоящее хранилище. Проверяем один раз: ответ не меняется. */
let real: boolean | null = null;

function usable(): boolean {
  if (real !== null) return real;
  try {
    // Не просто наличие объекта: в закрытом хранилище он есть, но всякое
    // обращение к нему бросает. Пробуем настоящую запись и уборку за собой.
    const probe = '__doton_probe__';
    localStorage.setItem(probe, '1');
    localStorage.removeItem(probe);
    real = true;
  } catch {
    real = false;
  }
  return real;
}

export function readStore(key: string): string | null {
  if (!usable()) return fallback.get(key) ?? null;
  try {
    return localStorage.getItem(key);
  } catch {
    return fallback.get(key) ?? null;
  }
}

export function writeStore(key: string, value: string): void {
  fallback.set(key, value);
  if (!usable()) return;
  try {
    localStorage.setItem(key, value);
  } catch {
    // Место кончилось или хранилище закрыли на ходу — остаётся запасная
    // память вкладки, и это лучше, чем оборванная игра.
  }
}

export function dropStore(key: string): void {
  fallback.delete(key);
  if (!usable()) return;
  try {
    localStorage.removeItem(key);
  } catch {
    // См. выше: забыть в запасной памяти уже забыли.
  }
}
