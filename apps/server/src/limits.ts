/**
 * Пороги правдоподобия — в одном месте.
 *
 * Их проверяют дуэль, пересчёт цепочек и пересчёт тапа. Пока значения
 * лежали копиями в трёх модулях, любое изменение молча расходилось: строже
 * стало в одном месте, а обойти можно было через другое. Правило одно на
 * всех — и константа одна.
 */

/** Минимальный интервал между ходами: человек физически не жмёт чаще. */
export const MIN_MOVE_GAP = 0.1;

/**
 * Не чаще одного жетона в столько секунд.
 *
 * Жетон даётся за доведённый до конца заход, и его нельзя заработать
 * быстрее, чем заход идёт. Самый короткий честный — тап, оборвавшийся на
 * трёх пустых окнах подряд: три раза по восемнадцать секунд. Отсюда и
 * порог: он не заденет ни одного игрока, но скрипту, шлющему один и тот же
 * журнал по кругу, оставляет ту же скорость, что и человеку за прибором.
 */
export const TOKEN_GAP_SECONDS = 50;

/**
 * Пороги, за которыми заход перестаёт быть похожим на человеческий.
 *
 * Оба выведены измерением на приборе, а не назначены на глаз (см. `judge.ts`
 * ядра). Ни один из них ничего не запрещает: прибор лишь замечает и зовёт
 * служащего — решает человек.
 *
 * **Острота** — средняя доля от самой длинной цепочки, доступной на поле.
 * Рука, берущая первую попавшуюся тройку, держит 0.45; сильная рука,
 * находящая лучшее каждый третий ход, — 0.61; перебор — ровно 1.00. Порог
 * стоит в пропасти между ними: чтобы дотянуться до 0.9, человеку надо
 * находить самую длинную змейку пять раз из шести подряд.
 *
 * **Ровность** — разброс промежутков между ходами к их среднему. У руки он
 * гуляет вдвое-втрое (0.4 и выше), у метронома стремится к нулю.
 *
 * Короткие заходы не судим вовсе: на трёх ходах и острота, и ровность —
 * случайность, а не почерк.
 */
export const JUDGE_MIN_MOVES = 10;
export const SHARP_LIMIT = 0.9;
export const PACE_LIMIT = 0.08;

/**
 * Сколько гостевых аккаунтов можно завести с одного адреса за час.
 *
 * Гостевой вход — единственная дверь, за которой нет ни пароля, ни
 * подписи: один запрос — одна строка в базе и одно место в таблицах.
 * Порог щедрый — его не заметит ни общий Wi-Fi, ни выход через NAT, — но
 * скрипт, набивающий таблицу тысячей имён, упирается в него сразу.
 */
export const SIGNUP_LIMIT = 60;
export const SIGNUP_WINDOW_MS = 60 * 60 * 1000;

/**
 * Общий потолок запросов с одного адреса, шт/мин.
 *
 * Он не про справедливость, а про то, чтобы одна машина не завалила
 * сервер: игре хватает пары десятков запросов в минуту (опрос
 * приглашений раз в пять секунд — двенадцать), а за одним адресом
 * мобильного оператора сидят десятки живых игроков, и порог обязан
 * пропускать их всех. Скрипт же, льющий сотни запросов в секунду,
 * упирается в потолок сразу.
 */
export const REQUEST_LIMIT = 1200;
export const REQUEST_WINDOW_MS = 60 * 1000;

/**
 * Сколько приглашений в Telegram шлёт один игрок за час.
 *
 * Позвать можно только друга, и это уже отсекает рассылку кому попало.
 * Но добавленный друг — это дверь, через которую можно долбить человека
 * сообщениями бесконечно; десятка вызовов в час хватает на любой вечер.
 */
export const INVITE_LIMIT = 10;
export const INVITE_WINDOW_MS = 60 * 60 * 1000;

/**
 * Счётчик на память процесса: ключ → сколько и до какого момента.
 *
 * Общего хранилища тут намеренно нет. Матчмейкер и так живёт в памяти
 * одного процесса, так что второй инстанс всё равно потребует общего
 * состояния — вот тогда счётчик и переедет туда же.
 */
export class RateGuard {
  private readonly seen = new Map<string, { count: number; until: number }>();

  constructor(
    private readonly limit: number,
    private readonly windowMs: number,
  ) {}

  /** Отмечает попытку; false — с этого ключа пора притормозить. */
  allow(key: string, now = Date.now()): boolean {
    const entry = this.seen.get(key);
    if (!entry || entry.until <= now) {
      // Заодно подметаем протухшее: иначе карта росла бы с каждым ключом.
      if (this.seen.size > 1000) {
        for (const [seenKey, value] of this.seen) {
          if (value.until <= now) this.seen.delete(seenKey);
        }
      }
      this.seen.set(key, { count: 1, until: now + this.windowMs });
      return true;
    }
    entry.count += 1;
    return entry.count <= this.limit;
  }
}

/** Гостевой вход: единственная дверь, за которой нет ни пароля, ни подписи. */
export class SignupGuard extends RateGuard {
  constructor() {
    super(SIGNUP_LIMIT, SIGNUP_WINDOW_MS);
  }
}
