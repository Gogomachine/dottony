/**
 * Пороги правдоподобия — в одном месте.
 *
 * Их проверяют дуэль, пересчёт спринта, пересчёт комбо и досыл наработки.
 * Пока значения лежали копиями в четырёх модулях, любое изменение молча
 * расходилось: строже стало в одном месте, а обойти можно было через
 * другое. Правило одно на всех — и константа одна.
 */

/** Минимальный интервал между ходами: человек физически не жмёт чаще. */
export const MIN_MOVE_GAP = 0.1;

/**
 * Запас к темпу при досыле наработки: первый досыл приходит с накопленным
 * за сессию, да и часы клиента с серверными расходятся.
 */
export const MOVE_SLACK = 30;

/**
 * Потолок стоимости одного хода — грубая проверка досыла из режимов,
 * которые сервер не переигрывает. Даже самая длинная цепочка с каскадом
 * линз в резонансе не даёт и близко столько.
 */
export const MAX_POINTS_PER_MOVE = 20_000;

/**
 * Сколько гостевых аккаунтов можно завести с одного адреса за час.
 *
 * Гостевой вход — единственная дверь, за которой нет ни пароля, ни
 * подписи: один запрос — одна строка в базе и одно место в таблицах.
 * Порог щедрый — его не заметит ни общий Wi-Fi, ни выход через NAT, — но
 * скрипт, набивающий таблицу тысячей имён, упирается в него сразу.
 */
export const SIGNUP_LIMIT = 60;
export const SIGNUP_WINDOW_MS = 60 * 60 * 1000;

/**
 * Счётчик на память процесса: адрес → сколько и до какого момента.
 *
 * Общего хранилища тут намеренно нет. Матчмейкер и так живёт в памяти
 * одного процесса, так что второй инстанс всё равно потребует общего
 * состояния — вот тогда счётчик и переедет туда же.
 */
export class SignupGuard {
  private readonly seen = new Map<string, { count: number; until: number }>();

  /** Отмечает попытку; false — с этого адреса пора притормозить. */
  allow(address: string, now = Date.now()): boolean {
    const entry = this.seen.get(address);
    if (!entry || entry.until <= now) {
      // Заодно подметаем протухшее: иначе карта росла бы с каждым адресом.
      if (this.seen.size > 1000) {
        for (const [key, value] of this.seen) {
          if (value.until <= now) this.seen.delete(key);
        }
      }
      this.seen.set(address, { count: 1, until: now + SIGNUP_WINDOW_MS });
      return true;
    }
    entry.count += 1;
    return entry.count <= SIGNUP_LIMIT;
  }
}
