import type { Dial, Dials } from './dials.js';
import type { Creature } from './creature.js';
import type { DayLog, Mood } from './care.js';
import type { Hint } from './species.js';

/**
 * Что прибор показывает игроку.
 *
 * Живёт рядом с правилами, а не в общем протоколе, нарочно: существо и так
 * строка параметров, и лаборатория отдаёт ровно её. Заводить второй,
 * «сетевой» вид того же существа значило бы держать два описания одного и
 * того же и однажды разойтись между ними.
 *
 * Ничего лишнего сюда не попадает — и в первую очередь **комфорт**. Он
 * считается на сервере и остаётся там: пришли его клиенту, и вся игра в
 * уход кончится в тот же вечер, когда кто-нибудь откроет ответ сервера.
 */

/** Стекло инкубатора: в нём идёт рост. */
export interface IncubatorView {
  creature: Creature | null;
  /** Где стоят тумблеры прямо сейчас. */
  dials: Dials;
  /** Трогал ли игрок их сегодня — или это ещё утренний сброс. */
  set: boolean;
  /** Сколько раз покормлено за сегодня. */
  feeds: number;
  /** Что видно на существе: одно состояние, а не список жалоб. */
  mood: Mood;
  /** Во сколько раз медленнее идёт цикл анимации. */
  pace: number;
  /** Суток небрежения подряд и сколько их до беды. */
  neglect: number;
  death: number;
  /** Хороших суток на второй стадии и сколько нужно всего. */
  goodDays: number;
  grow: number;
  lostAt: string | null;
  /** Стрелки у тумблеров: сторону называют только издали. */
  hints: Record<Dial, Hint> | null;
}

/** Вся лаборатория одним ответом: три стекла, кошелёк и что было ночью. */
export interface LabView {
  day: string;
  incubator: IncubatorView;
  /** Два стекла хранения. Ровно одна пара для скрещивания — и ни одной лишней. */
  slots: [Creature | null, Creature | null];
  /** Архив: скрещивание отправляет туда обоих родителей. */
  collection: Creature[];
  /** Сколько стоит следующая точка. Ноль — первая, она даром. */
  seedCost: number;
  tokens: number;
  /** Что случилось, пока не заходили: по строке на сутки, новые сверху. */
  news: DayLog[];
}
