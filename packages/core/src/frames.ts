/**
 * Оправа полосы шильдиков — рамка с подложкой вокруг того места на корпусе,
 * где стоят имя и шильдики.
 *
 * Это единственное украшение, которое видно целиком и сразу: в матче полоса
 * занята соперником, и его оправа едет на твой прибор вместе с его
 * шильдиками. Поэтому за неё и можно брать жетоны — купленное должен видеть
 * кто-то, кроме хозяина, иначе это покупка в стол.
 *
 * Здесь только номера и названия: как именно оправа выглядит, знает клиент —
 * это его дело, а серверу нужно лишь проверить, что такая есть и что она
 * игроку положена. Номера заданы руками: по ним прибор помнит покупки, и
 * переставлять их местами уже нельзя.
 */

export interface Frame {
  id: string;
  /** Название материала — оно же подпись в кабинете. */
  name: string;
}

/**
 * Цена оправы в жетонах. Дороже наклейки втрое: наклеек на корпусе три, а
 * оправа одна и видна целиком — это самое заметное, что можно купить.
 * Полторы сотни жетонов — это вечера три за прибором.
 */
export const FRAME_PRICE = 150;

/**
 * Материалы. Золота среди них нет намеренно: золотом помечено первое место
 * в вечной таблице, и продавать похожий блеск значит продавать вид первого
 * места.
 */
export const FRAMES: readonly Frame[] = [
  { id: 'f-brass', name: 'ЛАТУНЬ' },
  { id: 'f-chrome', name: 'ХРОМ' },
  { id: 'f-jade', name: 'НЕФРИТ' },
  { id: 'f-signal', name: 'СИГНАЛ' },
];

const BY_ID = new Map(FRAMES.map((frame) => [frame.id, frame]));

export function frameById(id: string): Frame | undefined {
  return BY_ID.get(id);
}

/** Есть ли такая оправа в каталоге. Носить её — отдельный вопрос. */
export function isFrame(id: string): boolean {
  return BY_ID.has(id);
}

/**
 * Оправа, которую можно показать: своя купленная либо ничего. Чужую и
 * выдуманную гасим здесь же — и на клиенте, и на сервере одинаково.
 */
export function frameAllowed(id: string | null, owned: readonly string[] = []): boolean {
  if (id === null) return true;
  return BY_ID.has(id) && owned.includes(id);
}
