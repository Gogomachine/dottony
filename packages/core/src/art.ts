/**
 * Рисунок игрока: лист прибора, каким он уезжает на пропуск и на экран
 * соперника.
 *
 * Всё остальное на приборе выбирают из закрытых наборов — наклейки,
 * оправы, смайлики, — и подделать там нечего. Здесь впервые наоборот:
 * картинку рисует человек. Поэтому у неё жёсткая форма, и лежит она в
 * ядре: клиент по этому файлу рисует, сервер по нему же проверяет
 * присланное, и разойтись им негде.
 *
 * Форма нарочно тесная — десять на десять клеток и десять красок. В такой
 * сетке помещается знак, а не сообщение: разборчивого текста не набрать,
 * лица не нарисовать. Это не защита от дурного рисунка (её здесь нет и
 * быть не может), а способ держать цену ошибки низкой — на чужом экране
 * шильдик занимает тринадцать точек.
 */

/**
 * Сторона листа. Не столько же, сколько на поле, и это меряно: один и тот
 * же мотив разложен по сеткам от шести до шестнадцати клеток и посмотрен в
 * натуральную величину шильдика.
 *
 * Шильдику мелкая сетка не мешает, а помогает: в тринадцати пикселях глаз
 * видит не точки, а контур, и чем он плавнее, тем понятнее картинка. Упор
 * оказался в руку. При десяти клетках на окуляр телефона приходится по
 * 28 точек на клетку — палец ведёт цепочку уверенно; при двенадцати уже
 * задевает соседей, при шестнадцати рисовать мучительно, да и кот там
 * занимает полтораста клеток вместо полусотни.
 */
export const ART_SIZE = 10;

/**
 * Краски листа. Первые четыре — цвета точек прибора, дальше идут те,
 * которых на поле не бывает: в игре четыре цвета — правило, а на листе
 * рисуют, и лишний оттенок там ничего не ломает.
 *
 * Порядок не переставляем: рисунок хранится номерами красок, и перестановка
 * молча перекрасила бы уже нарисованное — в том числе то, что игрок купил и
 * носит. Новые краски дописываются в конец.
 *
 * Белой краски среди них нет: белым на листе светится набранная цепочка —
 * нить и обводки, — и краска того же цвета спорила бы с ней. Чистое место
 * тоже белым не бывает: оно просто чёрное стекло.
 */
export const ART_PAINTS: readonly { name: string; css: string }[] = [
  { name: 'Янтарь', css: '#E3AE45' },
  { name: 'Нефрит', css: '#3F9C79' },
  { name: 'Коралл', css: '#D9584A' },
  { name: 'Лазурь', css: '#4589C4' },
  { name: 'Сигнал', css: '#E84B23' },
  { name: 'Слива', css: '#7C5C9E' },
  { name: 'Бирюза', css: '#2F8E8E' },
  { name: 'Умбра', css: '#9C6B3F' },
  { name: 'Роза', css: '#E08FA8' },
  { name: 'Графит', css: '#4A4A46' },
];

/** Клетка листа: номер краски либо чистое место. */
export type ArtCell = number | null;

/** Длина записи: клетка — один знак, строки идут подряд. */
export const ART_LEN = ART_SIZE * ART_SIZE;

/** Чистое место в записи. Точка, а не пробел: пробел теряется в адресах. */
const BLANK = '.';

/**
 * Номера красок пишутся одним знаком по счёту 0–9, a–z. Так рисунок
 * остаётся строкой ровно в сто знаков — её можно положить в колонку, в
 * ответ таблицы и в сообщение матча, не считая каждый раз длину.
 */
const DIGITS = '0123456789abcdefghijklmnopqrstuvwxyz';

export function artEmptyCells(): ArtCell[][] {
  return Array.from({ length: ART_SIZE }, () => Array.from({ length: ART_SIZE }, () => null));
}

/** Рисунок строкой. Клетки не по размеру и мусор в них — чистое место. */
export function encodeArt(cells: readonly (readonly ArtCell[])[]): string {
  let out = '';
  for (let r = 0; r < ART_SIZE; r++) {
    for (let c = 0; c < ART_SIZE; c++) {
      const value = cells[r]?.[c] ?? null;
      const digit =
        value !== null && Number.isInteger(value) && value >= 0 && value < ART_PAINTS.length
          ? DIGITS[value]
          : undefined;
      out += digit ?? BLANK;
    }
  }
  return out;
}

/** Разбирает запись обратно в клетки. Битую читаем как чистый лист. */
export function decodeArt(art: string): ArtCell[][] {
  const cells = artEmptyCells();
  if (!isArt(art)) return cells;
  for (let index = 0; index < ART_LEN; index++) {
    const digit = DIGITS.indexOf(art[index] ?? BLANK);
    if (digit >= 0) cells[Math.floor(index / ART_SIZE)]![index % ART_SIZE] = digit;
  }
  return cells;
}

/**
 * Годится ли запись к хранению. Проверяем и длину, и каждый знак: краска с
 * номером из будущего нарисовалась бы дыркой, а рисунок с дырками игрок
 * купил бы, не увидев.
 */
export function isArt(value: unknown): value is string {
  if (typeof value !== 'string' || value.length !== ART_LEN) return false;
  for (const char of value) {
    if (char === BLANK) continue;
    const digit = DIGITS.indexOf(char);
    if (digit < 0 || digit >= ART_PAINTS.length) return false;
  }
  return true;
}

/** Сколько клеток закрашено. Ноль — на пропуск такое ставить нечего. */
export function artPainted(art: string): number {
  if (!isArt(art)) return 0;
  let count = 0;
  for (const char of art) if (char !== BLANK) count += 1;
  return count;
}
