/**
 * Смайлики на пропуск — то, чем игрок помечает своё лицо.
 *
 * Набор закрытый, по той же причине, что и каталог шильдиков: аватар видит
 * соперник, а место под фото рассчитано на один знак. Свободный ввод пускал
 * туда и буквы, и склейки из нескольких значков, и наборы, которых на чужом
 * устройстве может не оказаться вовсе, — и модерировать это было бы нечем.
 *
 * Лежит в ядре не потому, что это правило игры, а потому, что это
 * единственный общий модуль, из которого значения берут и клиент, и сервер:
 * клиент рисует по нему сетку выбора, сервер по нему же проверяет, что
 * присланный смайлик вообще существует.
 */

/**
 * Только лица и головы: они читаются как портрет в рамке пропуска. Ни рук,
 * ни жестов, ни флагов — на чужом экране это должно быть лицом, а не
 * сообщением.
 */
export const FACES: readonly string[] = [
  '😀', '😃', '😄', '😁', '😆', '😅', '😂',
  '🙂', '🙃', '😉', '😊', '😇', '🥰', '😍',
  '🤩', '😋', '😜', '🤪', '🤨', '🧐', '🤓',
  '😎', '🥳', '😏', '😌', '😔', '🤔', '🤗',
  '😐', '😴', '🤠', '😈', '👻', '🤖', '👽',
];

const KNOWN = new Set(FACES);

/** Есть ли такой смайлик в наборе. Всё, что не из него, прибор не принимает. */
export function isFace(value: string): boolean {
  return KNOWN.has(value);
}
