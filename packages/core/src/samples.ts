import { ART_LEN, ART_SIZE, isArt } from './art.js';

/**
 * Образцы для листа: готовые картинки из точек, которые можно обвести.
 *
 * Чистое стекло — честное начало, но перед ним человек чаще всего замирает:
 * рисовать десятью красками в сотне клеток можно что угодно, и именно
 * поэтому непонятно, с чего начать. Образец отвечает на это не советом, а
 * примером: вот кот, вот рыба — обведи и увидишь, что сетка умеет.
 *
 * Правило набора: **одиночных клеток в образце не бывает**. Красит цепочка
 * от двух клеток, и одинокую точку одним движением не поставить — её
 * пришлось бы закрашивать парой и половину закрывать сверху. Поэтому у
 * каждой клетки образца есть соседка того же цвета — хотя бы по диагонали.
 *
 * Номера красок — из `ART_PAINTS`: 0 янтарь, 1 нефрит, 2 коралл, 3 лазурь,
 * 4 сигнал, 5 слива, 6 бирюза, 7 умбра, 8 роза, 9 графит. Точка — пустая
 * клетка, то есть чёрное стекло.
 *
 * Графита в образцах нет намеренно: стекло прибора чёрное, и графитовая
 * фигура на нём читается как пятно, а не как рисунок. Игроку эта краска
 * по-прежнему доступна — а вот звать ею в первый раз незачем.
 */

export interface Sample {
  /** Название — оно же подпись в приборной строке, пока образец на стекле. */
  name: string;
  /** Рисунок в той же записи, что и свой шильдик: сто знаков. */
  art: string;
}

/** Собирает строку образца из десяти рядов — так его видно прямо в коде. */
function rows(...lines: string[]): string {
  const art = lines.join('');
  // Ошибиться на клетку в такой записи легче лёгкого, а увидеть это на
  // стекле — трудно: сломанный образец просто съедет на ряд.
  if (lines.length !== ART_SIZE || art.length !== ART_LEN) {
    throw new Error(`образец не ${ART_SIZE}×${ART_SIZE}`);
  }
  return art;
}

