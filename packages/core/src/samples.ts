/**
 * Следующий образец по кругу; после последнего — чистое стекло (null), и
 * только потом первый. Пустое место в круге обязательно: убрать подложку
 * должно быть так же просто, как её позвать.
 */
export function nextSample(current: number | null): number | null {
  if (current === null) return SAMPLES.length > 0 ? 0 : null;
  return current + 1 < SAMPLES.length ? current + 1 : null;
}

/** Образец по номеру; null — его нет, и подложки на стекле тоже. */
export function sampleAt(index: number | null): Sample | null {
  if (index === null) return null;
  return SAMPLES[index] ?? null;
}

/** Все ли образцы записаны как надо. Зовётся тестом, а не игрой. */
export function samplesValid(): boolean {
  return SAMPLES.every((sample) => isArt(sample.art));
}
