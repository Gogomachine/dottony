/**
 * Шильдики на корпусе прибора — то, чем игрок его помечает.
 *
 * Набор закрытый: игрок ничего не вводит от себя, он выбирает из каталога.
 * Поэтому и подделать нечего, и модерировать нечего — в общие таблицы и на
 * экран соперника едет номер из этого файла, а рисует его клиент сам.
 *
 * Каталог лежит в ядре не потому, что это правило игры, а потому, что это
 * единственный общий модуль, из которого значения берут и клиент, и
 * сервер: сервер по нему проверяет, что выбранный шильдик существует и
 * положен игроку.
 */

export type MarkKind =
  /** Служебный шильдик: набитая на корпусе краска. Есть у всех. */
  | 'plate'
  /** Наклейка: смайл на маленькой белой наклейке. Есть у всех. */
  | 'sticker';

export interface Mark {
  id: string;
  kind: MarkKind;
  /** Что нарисовано: надпись для шильдика, смайл для наклейки. */
  glyph: string;
}

/** Сколько шильдиков помещается на корпусе. */
export const MARK_SLOTS = 3;

/**
 * Служебные шильдики — язык самого прибора. Их дело не украшать, а не
 * оставлять корпус пустым: первая ячейка бесплатна, и положить в неё что-то
 * уместное игрок должен с первого запуска.
 */
const PLATES: readonly string[] = [
  '36',
  'ОТК',
  'RT',
  '∅',
  'II',
  'III',
  '24В',
  '36/4',
  '°C',
  'СЕР.А',
  'ГОСТ',
  'РЕЗ.',
];

/**
 * Наклейки. Смайлы отобраны так, чтобы ни один не читался как жест или
 * знак принадлежности: на чужом экране всё это должно быть просто
 * картинкой, а не сообщением.
 */
const STICKERS: readonly string[] = [
  '🔭', '🔬', '⚗️', '🧪', '🧲', '💡', '🔋', '📡', '🛰️', '⏱️',
  '📈', '🧭', '⚙️', '🔧', '🪛', '📐', '📎', '🔎', '🎯', '🎲',
  '🧩', '♟️', '🎈', '🍀', '🌵', '🐢', '🐌', '🦔', '🦉', '🐙',
  '🍄', '🌗', '⭐', '⚡️', '🔥', '❄️', '🌊', '🪐', '☄️', '🛸',
  '🤖', '👾', '🧿', '🎧', '📻', '☕️',
];

/** Весь каталог: номер шильдика — его место в этом списке. */
export const MARKS: readonly Mark[] = [
  ...PLATES.map((glyph, index) => ({ id: `p${index}`, kind: 'plate' as const, glyph })),
  ...STICKERS.map((glyph, index) => ({ id: `s${index}`, kind: 'sticker' as const, glyph })),
];

const BY_ID = new Map(MARKS.map((mark) => [mark.id, mark]));

export function markById(id: string): Mark | undefined {
  return BY_ID.get(id);
}

/**
 * Положен ли шильдик игроку. Пока весь каталог бесплатный, но проверка
 * живёт здесь с самого начала: отметки за игру добавятся сюда же, и
 * сервер не должен будет вспоминать, где у него это правило.
 */
export function markAllowed(id: string): boolean {
  return BY_ID.has(id);
}

/**
 * Приводит выбор игрока к тому, что можно хранить: не длиннее корпуса,
 * без повторов и без несуществующих номеров. Пустая ячейка — null.
 */
export function cleanMarks(slots: readonly (string | null)[]): (string | null)[] {
  const seen = new Set<string>();
  const out: (string | null)[] = [];
  for (const id of slots.slice(0, MARK_SLOTS)) {
    if (id === null || !markAllowed(id) || seen.has(id)) {
      out.push(null);
      continue;
    }
    seen.add(id);
    out.push(id);
  }
  while (out.length < MARK_SLOTS) out.push(null);
  return out;
}
