/** Золотой шильдик таблицы — его носит тот, кто её сейчас возглавляет. */
export function goldMark(board: 'order' | 'sprint'): string {
  return board === 'order' ? 'g-order' : 'g-sprint';
}

/** Отметка за лигу по её порядковому номеру; 0 — начальная, за неё не дают. */
export function leagueMark(tier: number): string | null {
  return tier >= 1 && tier <= 4 ? `e-lg${tier}` : null;
}

/**
 * Свой шильдик — тот самый лист, нарисованный руками. Он один на игрока и
 * ничем не заменяется: номер в каталоге у всех общий, а картинка у каждого
 * своя и едет отдельно от номера (см. `art.ts`).
 *
 * Цена — самая высокая в приборе, и намеренно: это единственная вещь,
 * которой больше ни у кого нет. Наклейку выбирают из готового, оправу
 * надевают на чужие шильдики, ячейку открывают — всё это у кого-то уже
 * есть и будет. Свой рисунок не повторяется.
 *
 * Три тысячи — это месяцы: жетон даётся за доведённый до конца заход, да
 * надбавка за первый заход дня, и выходит по три десятка в день у того,
 * кто играет каждый вечер. Редкость тут не обещана словом, а посчитана:
 * носят такой шильдик те, кто играл сотню вечеров, и в таблице это видно
 * без всякой подписи.
 */
export const OWN_PRICE = 3000;

/** Номер своего шильдика. Он один на всех: своя у него только картинка. */
export const OWN_MARK = 'own';

