import { DEFAULT_CONFIG, type GameConfig } from './types.js';

/**
 * Ежедневный пазл: одна доска на всех и двадцать пять ходов.
 *
 * Всё остальное в приборе меряется временем — спринт, заказы, дуэль,
 * турнир. Здесь времени нет вовсе, и это не послабление, а другая игра:
 * пока идут часы, игрок берёт первое, что увидел; когда ходов ровно
 * двадцать пять, он считает. Поэтому у пазла и доска общая: спорить
 * интересно не о том, кто быстрее, а о том, кто лучше разобрал один и тот
 * же расклад.
 *
 * Два режима, и разница между ними только в учёте:
 *
 * - **вызов дня** — доска дня, одна попытка, счёт идёт в таблицу;
 * - **свободно** — случайная доска, попыток сколько угодно, в таблицу не
 *   идёт ничего.
 */

/**
 * Сколько ходов даётся.
 *
 * Двадцать пять — это примерно в полтора раза больше, чем нужно, чтобы
 * собрать всё лёгкое, и примерно вдвое меньше, чем хочется. Меньше — и
 * расклад решает больше игрока; больше — и считать перестаёшь, потому что
 * любая ошибка отыгрывается следующим ходом.
 */
export const PUZZLE_MOVES = 25;

/**
 * День пазла — дата UTC, `ГГГГ-ММ-ДД`.
 *
 * Пояс тут свой, не как у турнира и смены: те открываются и закрываются по
 * московскому времени, потому что это **события дня** — к ним приходят в
 * определённый час. Пазл не событие: доска лежит целые сутки и ждёт. Для
 * такого честнее всемирный полдень, чем чей-то местный, — иначе «доска
 * дня» у соседей по таблице оказывается вчерашней.
 */
export function puzzleDay(now: Date = new Date()): string {
  return now.toISOString().slice(0, 10);
}

/** Соседний день: `+1` — завтрашний, `-1` — вчерашний. */
export function puzzleDayShift(day: string, days: number): string {
  const shifted = new Date(`${day}T00:00:00Z`);
  shifted.setUTCDate(shifted.getUTCDate() + days);
  return shifted.toISOString().slice(0, 10);
}

/**
 * Сид доски дня — из самой даты, а не из базы.
 *
 * У турнира сид лежит строкой в базе: он случайный, и помнить его больше
 * негде. Пазлу хранить нечего — дата и есть сид, и это важнее, чем кажется:
 * клиент разворачивает доску сам, ещё до первого ответа сервера, а сервер
 * пересчитывает её независимо и потому не верит присланному сиду вовсе.
 *
 * Хеш настоящий, с перемешиванием: соседние даты различаются одним знаком,
 * и слабая свёртка дала бы соседним дням похожие расклады.
 */
export function puzzleSeed(day: string): number {
  let hash = 0x811c9dc5 >>> 0;
  for (let i = 0; i < day.length; i++) {
    hash = Math.imul(hash ^ day.charCodeAt(i), 0x01000193) >>> 0;
  }
  hash = Math.imul(hash ^ (hash >>> 16), 0x7feb352d) >>> 0;
  hash = Math.imul(hash ^ (hash >>> 15), 0x846ca68b) >>> 0;
  return (hash ^ (hash >>> 16)) >>> 0;
}

/**
 * Правила пазла: те же цепочки, но без всего, что считает секунды.
 *
 * Фазы «нагрузки сети» и заявка на цвет выключены не для простоты, а
 * потому, что они бессмысленны без часов: фаза приходит раз в сорок пять
 * секунд, и в партии, где время стоит, она либо не придёт никогда, либо
 * будет идти вечно. Перегрузка остаётся — она считает ходы, а не секунды,
 * и как раз за неё в пазле и играют: длинная цепочка оставляет заряд,
 * который окупится через ход-другой.
 */
