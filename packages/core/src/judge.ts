import type { Board, Cell, GameConfig } from './types.js';

/**
 * Чем ход человека отличается от хода решателя.
 *
 * Сервер и так переигрывает каждый заход ядром и потому знает, что ходы
 * **законны**. Но он не знает, что их сделал **человек**: скрипт, считающий
 * поле, играет по тем же правилам — просто лучше и бесконечно. Пока ставка
 * была самолюбием, это терпелось; в турнире на кону жетоны, и мерить
 * человечность приходится отдельно.
 *
 * Мерить прямо нечем — но есть косвенное, и оно на удивление твёрдое:
 * **человек не находит лучшего хода**. Самая длинная цепочка на поле почти
 * всегда вьётся змейкой через полполя, и увидеть её за секунду нельзя.
 * Измерено на приборе: рука, берущая первую попавшуюся тройку, держит долю
 * 0.45 от лучшего; сильная рука, находящая лучшее каждый третий ход, —
 * 0.61; перебор, берущий лучшее всегда, — ровно 1.00. Между сильным
 * человеком и решателем лежит пропасть, и порог ставится в ней.
 *
 * Это не доказательство и не приговор: прибор только замечает и зовёт
 * служащего. Решает человек — потому что ошибиться тут стоит дороже, чем
 * пропустить.
 */

/**
 * Потолок перебора при поиске самой длинной цепочки.
 *
 * Путей на поле бывает астрономически много (одноцветное пятно в дюжину
 * точек даёт миллионы), а ответ нужен приблизительный: доля от лучшего с
 * точностью до сотых. Замерено: с этим запасом поле считается за полмиллисекунды
 * и упирается в потолок два раза из трёхсот, а найденная длина совпадает с
 * полным перебором.
 */
export const CHAIN_SEARCH_BUDGET = 20_000;

/**
 * Длина самой длинной цепочки, которую можно провести на этом поле.
 *
 * Перебор в глубину от каждой клетки: цепочка — простой путь по соседним
 * точкам одного цвета, тем же соседством в восемь сторон, что и у игрока.
 * При упоре в потолок возвращается лучшее найденное — для доли этого хватает,
 * а завышенная доля (сыграно длиннее, чем мы нашли) просто зажимается в
 * единицу теми, кто её считает.
 */
export function longestChain(board: Board, cfg: GameConfig): number {
  let best = 0;
  let spent = 0;
  const seen = new Set<number>();
  const at = (r: number, c: number): number | undefined => board.grid[r]?.[c]?.color;
  const key = (cell: Cell): number => cell.r * cfg.cols + cell.c;

  const walk = (cell: Cell, color: number, depth: number): void => {
    if (spent++ > CHAIN_SEARCH_BUDGET) return;
    if (depth > best) best = depth;
    for (let dr = -1; dr <= 1; dr++) {
      for (let dc = -1; dc <= 1; dc++) {
        if (dr === 0 && dc === 0) continue;
        const next: Cell = { r: cell.r + dr, c: cell.c + dc };
        if (at(next.r, next.c) !== color) continue;
        const id = key(next);
        if (seen.has(id)) continue;
        seen.add(id);
        walk(next, color, depth + 1);
        seen.delete(id);
      }
    }
  };

  for (let r = 0; r < cfg.rows; r++) {
    for (let c = 0; c < cfg.cols; c++) {
      const color = at(r, c);
      if (color === undefined) continue;
      const start: Cell = { r, c };
      seen.clear();
      seen.add(key(start));
      walk(start, color, 1);
    }
  }
  return best;
}

/**
 * Ровность темпа: разброс промежутков между ходами, делённый на средний
 * промежуток.
 *
 * Человек ведёт цепочку рывками — нашёл, провёл, снова ищет, — и промежутки
 * гуляют вдвое-втрое. Скрипт шлёт ходы метрономом: либо через один и тот же
 * промежуток, либо через минимально допустимый. Ноль означает «идеально
 * ровно», то есть заведомо не рука.
 *
 * Меньше двух ходов мерить нечего — там нет ни одного промежутка.
 */
export function paceSpread(times: readonly number[]): number | null {
  if (times.length < 3) return null;
  const gaps: number[] = [];
  for (let i = 1; i < times.length; i++) gaps.push(times[i]! - times[i - 1]!);
  const mean = gaps.reduce((sum, gap) => sum + gap, 0) / gaps.length;
  if (mean <= 0) return 0;
  const variance = gaps.reduce((sum, gap) => sum + (gap - mean) ** 2, 0) / gaps.length;
  return Math.sqrt(variance) / mean;
}
