/**
 * Сборка. Одинаковые клетки в строке склеиваются в один прямоугольник —
 * иначе на каждую наклейку выходит по двести с лишним тегов, а весь набор
 * едет в бандл целиком.
 */
function toSvg(rows) {
  const parts = [];
  for (const [y, row] of rows.entries()) {
    let x = 0;
    while (x < SIZE) {
      const ch = row[x];
      if (ch === '.') {
        x += 1;
        continue;
      }
      let width = 1;
      while (x + width < SIZE && row[x + width] === ch) width += 1;
      parts.push(`<rect x="${x}" y="${y}" width="${width}" height="1" fill="${PALETTE[ch]}"/>`);
      x += width;
    }
  }
  return [
    '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 16 16" width="64" height="64"',
    ' shape-rendering="crispEdges">',
    parts.join(''),
    '</svg>\n',
  ].join('');
}

mkdirSync(OUT, { recursive: true });
for (const { file, rows } of ICONS) {
  writeFileSync(resolve(OUT, file), toSvg(rows));
}
