const SIZE = 16;

/**
 * Наклейки. Порядок здесь — порядок в каталоге прибора; номера (`id`)
 * задаёт `packages/core/src/marks.ts`, и менять их местами нельзя: по
 * номеру игрок владеет купленным.
 */
const ICONS = [];

/** Добавляет наклейку и тут же проверяет её сетку: кривую карту не пропускаем. */
function icon(file, rows) {
  if (rows.length !== SIZE) throw new Error(`${file}: строк ${rows.length}, а нужно ${SIZE}`);
  for (const [index, row] of rows.entries()) {
    if (row.length !== SIZE) throw new Error(`${file}: строка ${index + 1} длиной ${row.length}`);
    for (const ch of row) {
      if (ch !== '.' && PALETTE[ch] === undefined) throw new Error(`${file}: нет краски «${ch}»`);
    }
  }
  ICONS.push({ file, rows });
}

