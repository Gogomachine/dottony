/**
 * Рисовалка наклеек: из пиксельных карт делает SVG в `apps/client/public/marks/`.
 *
 * Наклейка на корпусе — тринадцать точек в поперечнике, и рисовать её мышью
 * бессмысленно: всё, что тоньше пикселя, там пропадёт. Поэтому картинка
 * задаётся прямо здесь — сеткой 16×16, буква на клетку, — а SVG собирается
 * из неё. Так рисунок можно править построчно и видеть его в тексте, а на
 * экране он остаётся чётким на любом увеличении: в SVG едут не точки, а
 * прямоугольники.
 *
 * Запуск: `node tools/marks/build.mjs`
 *
 * Палитра общая на все наклейки — иначе полтора десятка картинок в одном
 * каталоге разъезжаются по оттенкам, и набор перестаёт быть набором.
 * Цвета взяты от прибора: янтарь, нефрит, коралл, лазурь, сигнальный.
 */

